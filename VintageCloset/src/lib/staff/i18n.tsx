type Lang = 'de' | 'ar';

interface I18nValue {
  lang: Lang;
  dir: 'ltr' | 'rtl';
  t: (key: StaffKey) => string;
  toggle: () => void;
}

const I18nContext = createContext<I18nValue | null>(null);
const LANG_KEY = 'vc-staff-lang';

function readLang(): Lang {
  try {
    return typeof window !== 'undefined' && window.localStorage.getItem(LANG_KEY) === 'ar' ? 'ar' : 'de';
  } catch {
    return 'de';
  }
}

export function StaffI18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(readLang);
  const t = useCallback((key: StaffKey) => (lang === 'ar' ? ar[key] : de[key]) ?? key, [lang]);
  const toggle = useCallback(() => {
    setLang((prev) => {
      const next = prev === 'de' ? 'ar' : 'de';
      try {
        window.localStorage.setItem(LANG_KEY, next);
      } catch {
        /* storage blocked: language only for this visit */
      }
      return next;
    });
  }, []);
  return (
    <I18nContext.Provider value={{ lang, dir: lang === 'ar' ? 'rtl' : 'ltr', t, toggle }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useT() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useT must be used inside StaffI18nProvider');
  return ctx;
}
